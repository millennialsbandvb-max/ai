"""Gzip footboard_web/index.html into footboard_sticks3/fb_web.h (run after editing the page)."""
import gzip, os
here = os.path.dirname(os.path.abspath(__file__))
data = gzip.compress(open(os.path.join(here, 'footboard_web/index.html'), 'rb').read(), 9)
body = ',\n'.join(','.join(str(b) for b in data[i:i + 32]) for i in range(0, len(data), 32))
open(os.path.join(here, 'footboard_sticks3/fb_web.h'), 'w').write(
    f'// Generated by make_footboard_web.py\n#pragma once\n#include <pgmspace.h>\nstatic const uint8_t FB_INDEX_GZ[{len(data)}] PROGMEM = {{\n{body}\n}};\nstatic const size_t FB_INDEX_GZ_LEN = {len(data)};\n')
print('fb_web.h', len(data), 'bytes')
