/* is the installed browser the one this firmware lists (its packages.txt)? A card bundle has no list: keep it */
static int browser_current(void) {
    FILE *a = fopen(BROWSER_DIR "/packages.txt", "r"), *b = fopen("/usr/lib/nam-mpc/bin/browser-packages.txt", "r");
    int same = 1;
    if (a && b) {
        int ca, cb;
        do { ca = fgetc(a); cb = fgetc(b); } while (ca == cb && ca != EOF);
        same = ca == cb;
    }
    if (!a && access(BROWSER_DIR "/lib/libturbojpeg.so.0", R_OK)) same = 0;   /* an early install, before the MPC-screen view */
    if (a) fclose(a);
    if (b) fclose(b);
    return same;
}

static void browser_start(void) {
    if (browser_pid > 0 || install_pid > 0) return;
    if (access(BROWSER_DIR "/run.sh", R_OK) || !browser_current()) { start_after_install = 1; browser_install(); return; }
    const pid_t p = fork();
    if (p == 0) {
        setsid();
        const int fd = open("/tmp/mpc-browser.log", O_WRONLY | O_CREAT | O_TRUNC, 0644);
        if (fd >= 0) { dup2(fd, 1); dup2(fd, 2); }
        setpriority(PRIO_PROCESS, 0, 10);   /* MPC's audio always comes first */
        /* the firmware's own start script (an older install's copy may predate its settings) */
        execl("/bin/sh", "sh", access("/usr/lib/nam-mpc/bin/browser-run.sh", R_OK) ? BROWSER_DIR "/run.sh" :
              "/usr/lib/nam-mpc/bin/browser-run.sh", (char *)NULL);
        _exit(127);
    }
    if (p > 0) { browser_pid = p; browser_note[0] = 0; LOG("browser: started (pid %d)", (int)p); }
}

static void browser_stop(void) {
    if (browser_pid <= 0) return;
    kill(-browser_pid, SIGTERM);
    browser_stop_at = now_ms() + 4000;   /* then SIGKILL if it's still there */
    LOG("browser: stopping");
}

/* browser-install.sh downloads Chromium from Debian onto the MPC (or unpacks MPC-Browser.tar.gz from a card) */
static void browser_install(void) {
    if (browser_pid > 0 || install_pid > 0) return;
    struct statvfs v;
    if (!statvfs("/data", &v) && (unsigned long long)v.f_bavail * v.f_frsize < 700ull << 20) {
        snprintf(browser_note, sizeof browser_note, "not enough room on the MPC's internal storage (needs 700 MB)");
        return;
    }
    unlink("/tmp/mpc-browser-install");
    const pid_t p = fork();
    if (p == 0) {
        setpriority(PRIO_PROCESS, 0, 15);
        const int fd = open("/tmp/mpc-browser-install.log", O_WRONLY | O_CREAT | O_TRUNC, 0644);
        if (fd >= 0) { dup2(fd, 1); dup2(fd, 2); }
        execl("/bin/sh", "sh", "/usr/lib/nam-mpc/bin/browser-install.sh", (char *)NULL);
        _exit(127);
    }
    if (p > 0) { install_pid = p; snprintf(browser_note, sizeof browser_note, "installing"); LOG("browser: installing"); }
}

static void browser_reap(void) {   /* children that finished */
    int st;
    pid_t p;
    while ((p = waitpid(-1, &st, WNOHANG)) > 0) {
        if (p == browser_pid) {
            browser_pid = -1;
            snprintf(browser_note, sizeof browser_note, "browser stopped (%s %d; details: /log)",
                     WIFEXITED(st) ? "exit" : "signal", WIFEXITED(st) ? WEXITSTATUS(st) : WTERMSIG(st));
            LOG("browser: %s", browser_note);
            browser_status();
        } else if (p == install_pid) {
            install_pid = -1;
            const int ok = WIFEXITED(st) && !WEXITSTATUS(st);
            char last[256] = "";
            FILE *pf = fopen("/tmp/mpc-browser-install", "r");
            if (pf) { if (fgets(last, sizeof last, pf)) last[strcspn(last, "\n\"\\")] = 0; fclose(pf); }
            snprintf(browser_note, sizeof browser_note, "%s", ok ? "installed: press Start" : last[0] ? last : "install failed (details: /log)");
            LOG("browser: %s", browser_note);
            if (ok && start_after_install) browser_start();
            start_after_install = 0;
            browser_status();
        }
    }
    if (browser_pid > 0 && browser_stop_at && now_ms() > browser_stop_at) { kill(-browser_pid, SIGKILL); browser_stop_at = 0; }
}

static void cdp_json(Client *c) {   /* the browser's tabs (DevTools' /json/list) */
    const int fd = cdp_connect();
    if (fd < 0) { http_reply(c, "503 Service Unavailable", "text/plain", "browser not running\n", 20); return; }
    struct timeval tv = {3, 0};
    setsockopt(fd, SOL_SOCKET, SO_RCVTIMEO, &tv, sizeof tv);
    /* (DevTools doesn't answer HTTP/1.0, and may keep the connection open: read by Content-Length) */
    const char *rq = "GET /json/list HTTP/1.1\r\nHost: 127.0.0.1:9222\r\nConnection: close\r\n\r\n";
    if (write(fd, rq, strlen(rq)) < 0) { close(fd); return; }
    static char buf[65536];
    size_t n = 0;
    ssize_t r;
    const char *body = NULL;
    long len = -1;
    while (n < sizeof buf - 1 && (r = read(fd, buf + n, sizeof buf - 1 - n)) > 0) {
        n += (size_t)r;
        buf[n] = 0;
        if (!body && (body = strstr(buf, "\r\n\r\n"))) {
            body += 4;
            const char *cl = strcasestr(buf, "Content-Length:");
            if (cl && cl < body) len = atol(cl + 15);
        }
        if (body && len >= 0 && (long)(n - (size_t)(body - buf)) >= len) break;
    }
    close(fd);
    if (!body) { http_reply(c, "502 Bad Gateway", "text/plain", "no answer\n", 10); return; }
    http_reply(c, "200 OK", "application/json", body, n - (size_t)(body - buf));
}

