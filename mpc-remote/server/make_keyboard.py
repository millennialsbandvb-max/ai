#!/usr/bin/env python3
"""Draw the on-screen keyboard for the browser on the MPC's screen.
   make_keyboard.py <font.ttf> <out dir>
Writes keyboard_lower.jpg, keyboard_upper.jpg (W x KH) and keyboard.h: the keys' rectangles and what they type,
for mpc-remote (which shows the picture under the web page and turns touches on it into typing)."""
import sys
from PIL import Image, ImageDraw, ImageFont

W, KH = 1240, 236           # the MPC Browser page's area is 1240 wide
ROWS = [  # (label lower, label upper, kind, width units); kind: c = character, or a special key
    [("1", "!"), ("2", "@"), ("3", "#"), ("4", "$"), ("5", "%"), ("6", "^"), ("7", "&"), ("8", "*"), ("9", "("),
     ("0", ")"), ("-", "_"), ("=", "+"), ("Delete", "Delete", "backspace", 2)],
    [("q", "Q"), ("w", "W"), ("e", "E"), ("r", "R"), ("t", "T"), ("y", "Y"), ("u", "U"), ("i", "I"), ("o", "O"),
     ("p", "P"), ("[", "{"), ("]", "}"), ("/", "?", "c", 2)],
    [("a", "A"), ("s", "S"), ("d", "D"), ("f", "F"), ("g", "G"), ("h", "H"), ("j", "J"), ("k", "K"), ("l", "L"),
     (";", ":"), ("'", '"'), ("Enter", "Enter", "enter", 3)],
    [("Shift", "Shift", "shift", 2), ("z", "Z"), ("x", "X"), ("c", "C"), ("v", "V"), ("b", "B"), ("n", "N"),
     ("m", "M"), (",", "<"), (".", ">"), ("@", "@"), ("Shift", "Shift", "shift", 2)],
    [(".com", ".com", "text", 2), ("space", "space", "space", 8), ("<", "<", "left", 1), (">", ">", "right", 1),
     ("Hide", "Hide", "hide", 2)],
]
GAP, PAD = 6, 6
ROW_H = (KH - 2 * PAD - GAP * (len(ROWS) - 1)) // len(ROWS)


def layout():
    keys = []
    for r, row in enumerate(ROWS):
        units = sum(k[3] if len(k) > 3 else 1 for k in row)
        unit = (W - 2 * PAD + GAP) / units      # each unit is a key's width plus the gap after it
        x = PAD
        y = PAD + r * (ROW_H + GAP)
        for k in row:
            u = k[3] if len(k) > 3 else 1
            kind = k[2] if len(k) > 2 else "c"
            keys.append((round(x), y, round(x + unit * u - GAP) - round(x), ROW_H, k[0], k[1], kind))
            x += unit * u
    return keys


def draw(keys, upper, font, out):
    im = Image.new("RGB", (W, KH), (24, 24, 26))
    d = ImageDraw.Draw(im)
    for x, y, w, h, lo, up, kind in keys:
        fill = (58, 58, 62) if kind == "c" else (40, 40, 44)
        if kind == "shift" and upper:
            fill = (229, 116, 43)
        d.rounded_rectangle([x, y, x + w - 1, y + h - 1], radius=7, fill=fill)
        t = up if upper else lo
        f = font if len(t) == 1 or kind == "c" else font_small
        tw = d.textlength(t, font=f)
        d.text((x + (w - tw) / 2, y + h / 2), t, font=f, fill=(235, 235, 235), anchor="lm")
    im.save(out, quality=92)


font = ImageFont.truetype(sys.argv[1], 30)
font_small = ImageFont.truetype(sys.argv[1], 24)
keys = layout()
out = sys.argv[2]
draw(keys, False, font, out + "/keyboard_lower.jpg")
draw(keys, True, font, out + "/keyboard_upper.jpg")


def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


with open(out + "/keyboard.h", "w") as f:
    f.write("/* generated by make_keyboard.py: the browser's on-screen keyboard */\n")
    f.write(f"#define KB_W {W}\n#define KB_H {KH}\n")
    f.write("static const struct kb_key { short x, y, w, h; const char *lower, *upper, *kind; } KB_KEYS[] = {\n")
    for x, y, w, h, lo, up, kind in keys:
        # what a character key types (".com" types its label); special keys are handled by kind
        f.write(f"    {{{x}, {y}, {w}, {h}, {cstr(lo)}, {cstr(up)}, {cstr(kind)}}},\n")
    f.write("};\n")
    for name in ("lower", "upper"):
        data = open(f"{out}/keyboard_{name}.jpg", "rb").read()
        f.write(f"static const unsigned char KB_JPG_{name.upper()}[] = {{\n")
        for i in range(0, len(data), 24):
            f.write("  " + ",".join(str(b) for b in data[i:i + 24]) + ",\n")
        f.write("};\n")
# a small font for the address bar: ASCII 32..126, one strip of 8-bit coverage, FONT_H tall
FONT_H = 34
ff = ImageFont.truetype(sys.argv[1], 22)
advs, xs, x = [], [], 0
for c in range(32, 127):
    advs.append(max(1, round(ff.getlength(chr(c)))))
    xs.append(x)
    x += advs[-1]
atlas = Image.new("L", (x, FONT_H), 0)
ad = ImageDraw.Draw(atlas)
for i, c in enumerate(range(32, 127)):
    ad.text((xs[i], FONT_H // 2), chr(c), font=ff, fill=255, anchor="lm")
with open(out + "/keyboard.h", "a") as f:
    f.write(f"#define FONT_H {FONT_H}\n#define FONT_ATLAS_W {x}\n")
    f.write("static const short FONT_ADV[95] = {" + ",".join(map(str, advs)) + "};\n")
    f.write("static const int FONT_X[95] = {" + ",".join(map(str, xs)) + "};\n")
    data = atlas.tobytes()
    f.write("static const unsigned char FONT_ALPHA[] = {\n")
    for i in range(0, len(data), 32):
        f.write("  " + ",".join(str(b) for b in data[i:i + 32]) + ",\n")
    f.write("};\n")
print(f"keyboard: {len(keys)} keys, {W}x{KH}")
# the browser bar's icons (Chrome-like): back, forward, reload, home, star (outline), star (filled); ICON x ICON coverage
ICON = 30
S4 = ICON * 4


def icon(draw_fn):
    im = Image.new("L", (S4, S4), 0)
    draw_fn(ImageDraw.Draw(im), S4)
    return im.resize((ICON, ICON), Image.LANCZOS)


def arrow(d, s, left):
    w = s // 11
    y = s // 2
    x0, x1 = (s * 0.2, s * 0.8) if left else (s * 0.8, s * 0.2)
    d.line([(x0, y), (x1, y)], fill=255, width=w)
    k = s * 0.28 * (1 if left else -1)
    d.line([(x0, y), (x0 + k, y - abs(k))], fill=255, width=w)
    d.line([(x0, y), (x0 + k, y + abs(k))], fill=255, width=w)
    for p in ((x0, y),):
        d.ellipse([p[0] - w / 2, p[1] - w / 2, p[0] + w / 2, p[1] + w / 2], fill=255)


def reload_(d, s):
    w = s // 11
    m = s * 0.2
    d.arc([m, m, s - m, s - m], 40, 330, fill=255, width=w)
    import math
    a = math.radians(330)
    cx = cy = s / 2
    r = (s - 2 * m) / 2
    tx, ty = cx + r * math.cos(a), cy + r * math.sin(a)
    h = s * 0.2
    d.polygon([(tx - h * 0.2, ty - h), (tx + h, ty - h * 0.1), (tx - h * 0.1, ty + h * 0.55)], fill=255)


def home(d, s):
    w = s // 11
    d.line([(s * 0.15, s * 0.5), (s * 0.5, s * 0.17), (s * 0.85, s * 0.5)], fill=255, width=w, joint="curve")
    d.line([(s * 0.27, s * 0.42), (s * 0.27, s * 0.84), (s * 0.73, s * 0.84), (s * 0.73, s * 0.42)], fill=255, width=w, joint="curve")


def star(d, s, filled):
    import math
    pts = []
    for i in range(10):
        r = s * (0.42 if i % 2 == 0 else 0.18)
        a = math.radians(-90 + i * 36)
        pts.append((s / 2 + r * math.cos(a), s * 0.53 + r * math.sin(a)))
    if filled:
        d.polygon(pts, fill=255)
    else:
        d.line(pts + [pts[0]], fill=255, width=s // 14, joint="curve")


icons = [icon(lambda d, s: arrow(d, s, True)), icon(lambda d, s: arrow(d, s, False)), icon(reload_), icon(home),
         icon(lambda d, s: star(d, s, False)), icon(lambda d, s: star(d, s, True))]
with open(out + "/keyboard.h", "a") as f:
    f.write(f"#define ICON {ICON}\nenum {{ IC_BACK, IC_FORWARD, IC_RELOAD, IC_HOME, IC_STAR, IC_STAR_ON, IC_N }};\n")
    f.write("static const unsigned char ICON_ALPHA[IC_N][ICON * ICON] = {\n")
    for im in icons:
        f.write("  {" + ",".join(map(str, im.tobytes())) + "},\n")
    f.write("};\n")
strip = Image.new("L", (ICON * len(icons), ICON))
for i, im in enumerate(icons):
    strip.paste(im, (i * ICON, 0))
strip.save(out + "/icons.png")
